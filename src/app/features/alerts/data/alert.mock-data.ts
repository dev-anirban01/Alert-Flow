
import {
  Alert,
  AlertSeverity,
  AlertSource,
  AlertStatus,
  AlertHistory
} from '../models/alert.model';

const severities: AlertSeverity[] = [
  'CRITICAL',
  'HIGH',
  'MEDIUM',
  'LOW'
];

const statuses: AlertStatus[] = [
  'OPEN',
  'ESCALATED',
  'AUTO_CLOSED',
  'RESOLVED'
];

const sources: AlertSource[] = [
  'tracking-svc',
  'billing-svc',
  'auth-svc'
];

const titles = [
  'Payment processing failure',
  'Tracking service unavailable',
  'Authentication request failed',
  'High response time detected',
  'Billing transaction delayed',
  'Service connection timeout'
];

const descriptions = [
  'The service detected an unexpected error while processing a request.',
  'The monitoring system detected a service availability issue.',
  'Multiple authentication requests failed within a short time.',
  'The response time crossed the configured performance threshold.',
  'A billing transaction took longer than the expected time.',
  'The service could not establish a connection within the expected time.'
];

function createHistory(
  id: string,
  status: AlertStatus,
  createdAt: string
): AlertHistory[] {
  const history: AlertHistory[] = [
    {
      id: `${id}-H1`,
      state: 'OPEN',
      action: 'Alert created',
      ts: createdAt,
      timestamp: createdAt,
      description: 'Alert was generated by the monitoring system.',
      performedBy: 'Monitoring System'
    }
  ];

  if (status !== 'OPEN') {
    const nextState = status;
    const nextTimestamp = new Date(
      new Date(createdAt).getTime() + 5 * 60 * 1000
    ).toISOString();

    history.push({
      id: `${id}-H2`,
      state: nextState,
      action: status === 'ESCALATED'
        ? 'Alert escalated'
        : status === 'AUTO_CLOSED'
          ? 'Alert automatically closed'
          : 'Alert resolved',
      ts: nextTimestamp,
      timestamp: nextTimestamp,
      description: status === 'ESCALATED'
        ? 'Alert was escalated for further investigation.'
        : status === 'AUTO_CLOSED'
          ? 'Alert was automatically closed by the system.'
          : 'Alert was resolved by the operations team.',
      performedBy: status === 'AUTO_CLOSED'
        ? 'Monitoring System'
        : 'Admin User'
    });
  }

  return history;
}

export function createMockAlerts(): Alert[] {
  const now = Date.now();

  const alerts: Alert[] = Array.from(
    { length: 60 },
    (_, index) => {
      const number = index + 1;
      const id = `AL-${String(number).padStart(3, '0')}`;

      const createdAt = new Date(
        now - index * 12 * 60 * 1000
      ).toISOString();

      const status = statuses[index % statuses.length];

      return {
        id,
        title: titles[index % titles.length],
        description: descriptions[index % descriptions.length],
        source: sources[index % sources.length],
        severity: severities[index % severities.length],
        status,
        createdAt,
        updatedAt: createdAt,
        history: createHistory(id, status, createdAt)
      };
    }
  );

  // Assignment example: AL-042
  const example = alerts.find(
    alert => alert.id === 'AL-042'
  );

  if (example) {
    example.source = 'billing-svc';
    example.severity = 'HIGH';
    example.status = 'ESCALATED';
    example.createdAt = '2026-08-17T22:10:00Z';
    example.updatedAt = '2026-08-18T06:00:00Z';

    example.history = [
      {
        id: 'AL-042-H1',
        state: 'OPEN',
        action: 'Alert created',
        ts: '2026-08-17T22:10:00Z',
        timestamp: '2026-08-17T22:10:00Z',
        description: 'Alert was created by the monitoring system.',
        performedBy: 'Monitoring System'
      },
      {
        id: 'AL-042-H2',
        state: 'ESCALATED',
        action: 'Alert escalated',
        ts: '2026-08-18T06:00:00Z',
        timestamp: '2026-08-18T06:00:00Z',
        description: 'Alert was escalated for further investigation.',
        performedBy: 'Admin User'
      }
    ];
  }

  return alerts.sort(
    (a, b) =>
      new Date(b.createdAt).getTime() -
      new Date(a.createdAt).getTime()
  );
}
